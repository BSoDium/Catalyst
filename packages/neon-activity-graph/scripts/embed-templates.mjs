// Writes `src/templates-data.ts`: the baked caustic templates (assets/caustic-templates.png) as a data URI, so the package works with no asset pipeline.
// The module is only imported (dynamically) when the dark theme is first shown. Run by `pnpm build`; the output is committed so that the sources work as they are.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const png = readFileSync(fileURLToPath(new URL("../assets/caustic-templates.png", import.meta.url)));
const out = `// Generated by scripts/embed-templates.mjs from assets/caustic-templates.png: do not edit.\nexport const TEMPLATES_DATA_URI = "data:image/png;base64,${png.toString("base64")}";\n`;
writeFileSync(fileURLToPath(new URL("../src/templates-data.ts", import.meta.url)), out);
console.log(`templates-data.ts: ${png.length} bytes of PNG`);
